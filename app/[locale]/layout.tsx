import type { Metadata } from "next";
import { Work_Sans, Crimson_Text } from "next/font/google";
import { NextIntlClientProvider } from "next-intl";
import { getMessages, setRequestLocale } from "next-intl/server";
import { notFound } from "next/navigation";
import ReactLenis from "lenis/react";

import "./globals.css";
import NavBar from "@/components/common/NavBar";
import Footer from "@/components/common/Footer";

const workSans = Work_Sans({
  variable: "--font-work-sans",
  subsets: ["latin"],
});

const crimsonText = Crimson_Text({
  variable: "--font-crimson-text",
  subsets: ["latin"],
  weight: ["400", "600", "700"],
  style: ["normal", "italic"],
});

export const metadata: Metadata = {
  title: "Dubai Real Estate Pro",
  description: "Generated by HUNTRIX",
};

type Props = {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
};

export default async function LocaleLayout({ children, params }: Props) {

  const { locale } = await params;
  // Validate Locale
  if (!["en", "ar"].includes(locale)) {
    notFound();
  }
  // Set active locale
  setRequestLocale(locale);
  // Load Translations
  const messages = await getMessages();

  return (
    <html lang={locale} dir={locale === "ar" ? "rtl" : "ltr"}>
      <body
        className={`${workSans.variable} ${crimsonText.variable} antialiased`}
      >
        {/* Translation Provider */}

        <ReactLenis root>
          <NextIntlClientProvider messages={messages}>
            <main
              className="relative min-h-screen font-sans scroll-smooth"
              style={{ scrollbarGutter: "stable" }}
            >
              {/* Background */}
              <div className="w-full absolute inset-0 -z-10 bg-[url(/background.png)] bg-cover bg-center bg-no-repeat" />
              <NavBar />
              {children}
              <Footer />
            </main>
          </NextIntlClientProvider>
        </ReactLenis>
      </body>
    </html>
  );
}